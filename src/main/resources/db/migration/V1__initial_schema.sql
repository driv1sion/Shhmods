INSERT INTO tenant_config (tenant_id) VALUES ('GLOBAL');

-- ============================================================
-- 9. MODERATION LEDGER (V5)
-- ============================================================
CREATE TABLE moderation_event (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id VARCHAR(100) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    content_hash VARCHAR(64) NOT NULL,
    normalized_text TEXT,
    signals JSONB NOT NULL,
    policy_version INT NOT NULL,
    decision VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX idx_moderation_event_created_at_brin ON moderation_event USING BRIN(created_at);
CREATE INDEX idx_moderation_event_user_id ON moderation_event(user_id);

CREATE OR REPLACE FUNCTION prevent_ledger_tampering() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'Moderation ledger is immutable. UPDATE or DELETE operations are forbidden.';
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_moderation_event_immutable
BEFORE UPDATE OR DELETE ON moderation_event
FOR EACH ROW EXECUTE FUNCTION prevent_ledger_tampering();

-- ============================================================
-- 10. TEMPORAL TRUST DECAY (V7)
-- ============================================================
CREATE TABLE trust_event (
    event_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    compartment VARCHAR(50) NOT NULL,
    penalty DECIMAL(10,2) NOT NULL,
    decay_rate DECIMAL(15,10) NOT NULL,
    occurred_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX idx_trust_event_user_id ON trust_event(user_id, compartment);

CREATE VIEW effective_trust AS
SELECT 
    user_id, 
    compartment,
    GREATEST(0.0, 100.0 - SUM(
        penalty * exp(-decay_rate * EXTRACT(EPOCH FROM (now() - occurred_at)))
    )) AS current_trust
FROM trust_event
GROUP BY user_id, compartment;

-- ============================================================
-- 11. GRAPH COORDINATION CLUSTERS (V6)
-- ============================================================
CREATE MATERIALIZED VIEW coordination_clusters AS
WITH recent_reports AS (
    SELECT r.reporter_id, c.user_id AS target_id
    FROM report r
    JOIN content c ON r.content_id = c.content_id
    WHERE r.reported_at > NOW() - INTERVAL '24 hours'
),
reporter_pairs AS (
    SELECT
        r1.reporter_id AS reporter_a,
        r2.reporter_id AS reporter_b,
        count(*) AS shared_targets
    FROM recent_reports r1
    JOIN recent_reports r2
      ON r1.target_id = r2.target_id
     AND r1.reporter_id < r2.reporter_id
    GROUP BY r1.reporter_id, r2.reporter_id
)
SELECT reporter_a, reporter_b, shared_targets
FROM reporter_pairs
WHERE shared_targets >= 3;

CREATE INDEX idx_coordination_reporter_a ON coordination_clusters(reporter_a);
CREATE INDEX idx_coordination_reporter_b ON coordination_clusters(reporter_b);

CREATE MATERIALIZED VIEW content_clusters AS
WITH recent_content AS (
    SELECT user_id, content_hash
    FROM content
    WHERE created_at > NOW() - INTERVAL '1 hour'
),
poster_pairs AS (
    SELECT
        c1.user_id AS poster_a,
        c2.user_id AS poster_b,
        count(*) AS shared_hashes
    FROM recent_content c1
    JOIN recent_content c2
      ON c1.content_hash = c2.content_hash
     AND c1.user_id < c2.user_id
    GROUP BY c1.user_id, c2.user_id
)
SELECT poster_a, poster_b, shared_hashes
FROM poster_pairs
WHERE shared_hashes >= 2;

CREATE INDEX idx_content_poster_a ON content_clusters(poster_a);
CREATE INDEX idx_content_poster_b ON content_clusters(poster_b);

