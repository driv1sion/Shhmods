-- 12. GENERAL VIEWS (V4)
-- ============================================================
CREATE OR REPLACE VIEW vw_flagged_content AS
SELECT 
    f.flag_id,
    c.tenant_id,
    c.content_id,
    c.content_text,
    u.username AS author_name,
    f.flag_type,
    f.reason,
    f.status,
    f.report_count,
    f.flagged_at
FROM content_flag f
JOIN content c ON f.content_id = c.content_id
JOIN users u ON c.user_id = u.user_id
WHERE f.status != 'RESOLVED';

CREATE OR REPLACE VIEW vw_audit_log AS
SELECT 
    audit_id,
    action_type,
    action_details,
    reference_type,
    reference_id,
    actor_id,
    actor_type,
    action_timestamp
FROM audit_log
ORDER BY action_timestamp DESC;

CREATE OR REPLACE VIEW vw_top_users AS
SELECT 
    u.user_id,
    u.tenant_id,
    u.username,
    COALESCE(MIN(t.current_trust), 100.0) AS trust_score
FROM users u
LEFT JOIN effective_trust t ON u.user_id = t.user_id
GROUP BY u.user_id, u.tenant_id, u.username
HAVING COALESCE(MIN(t.current_trust), 100.0) > 80.0
ORDER BY trust_score DESC;
